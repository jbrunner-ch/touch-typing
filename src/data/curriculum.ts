export function getLessonText(lesson: Lesson, layoutId: KeyboardLayoutId): string {
  if (layoutId === 'en-qwerty') return lesson.texts.en;
  if (layoutId === 'ch-qwertz') {
    // Swiss German avoids 'ß', uses 'ss'
    return lesson.texts.de.replace(/ß/g, 'ss');
  }
  return lesson.texts.de;
}

